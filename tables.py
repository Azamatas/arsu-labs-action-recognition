"""Collect every result in results/ into RESULTS.md: mean +- s.d. over seeds (s.d. with ddof 1; '-' for one seed).

    python tables.py
"""
import glob
import json
import os
from collections import defaultdict

import numpy as np

from data_processing import daghar

ROOT = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(ROOT, "results")


def load():
    rows = []
    for f in glob.glob(os.path.join(RESULTS, "*", "*", "*", "seed*.json")):
        with open(f, encoding="utf-8") as fh:
            rows.append(json.load(fh))
    return rows


def ms(values, scale=100, digits=1):
    values = [v for v in values if v is not None]  # imported runs may lack macro F1
    if not values:
        return "-"
    v = scale * np.asarray(values, float)
    sd = f" ± {v.std(ddof=1):.{digits}f}" if len(v) > 1 else ""
    return f"{v.mean():.{digits}f}{sd}"


def seeds(rs):
    return ",".join(str(s) for s in sorted(r["seed"] for r in rs))


def cost(rs):
    r = rs[0]
    if "mflops_spectral" in r:
        return f"{r['params_spectral']:,} / {r['mflops_spectral']:.3f}"
    if "params" in r:
        return f"{r['params']:,}" + (f" / {r['mflops']:.3f}" if "mflops" in r else "")
    return ""


def per_test_tables(rows, protocol, title, best=False):
    lines = []
    by_variant = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r["protocol"] == protocol:
            by_variant[r["variant"]][r["model"]].append(r)
    for variant in sorted(by_variant):
        models = by_variant[variant]
        tests = list(next(iter(models.values()))[0]["scores"])
        lines += [f"### {title}: {variant}", ""]
        head = "| model | params / MFLOPs | seeds | " + " | ".join(f"{t}: acc / F1" for t in tests) + " |"
        if best:
            head = head[:-2] + " | " + " | ".join(f"{t}: acc at best val. epoch" for t in tests) + " |"
        lines += [head, "|---|---:|---|" + "---:|" * (len(tests) * (2 if best else 1))]
        for m in sorted(models):
            rs = models[m]
            cells = [f"{ms([r['scores'][t]['accuracy'] for r in rs])} / {ms([r['scores'][t]['macro_f1'] for r in rs])}"
                     for t in tests]
            if best:
                cells += [ms([r["scores_best"][t]["accuracy"] for r in rs if "scores_best" in r]) for t in tests]
            lines.append(f"| {m} | {cost(rs)} | {seeds(rs)} | " + " | ".join(cells) + " |")
        lines.append("")
    return lines


def daghar_table(rows):
    """Models x targets; the mean column averages the six targets per seed, then over the seeds that have all six."""
    lines = []
    for suffix, title in (("", "accelerometer + gyroscope"), ("-accel", "accelerometer only")):
        by_model = defaultdict(lambda: defaultdict(dict))
        for r in rows:
            if r["protocol"] == "daghar_lodo" and r["variant"] == r["variant"].split("-")[0] + suffix:
                by_model[r["model"]][r["seed"]][r["variant"].split("-")[0]] = r
        if not by_model:
            continue
        lines += [f"### DAGHAR leave-one-dataset-out, {title}: target accuracy %", "",
                  "| model | params / MFLOPs | seeds | " + " | ".join(daghar.DOMAINS) + " | mean |",
                  "|---|---:|---|" + "---:|" * (len(daghar.DOMAINS) + 1)]
        for m in sorted(by_model):
            per_seed = by_model[m]
            cells = []
            for t in daghar.DOMAINS:
                v = [per_seed[s][t]["scores"][t]["accuracy"] for s in per_seed if t in per_seed[s]]
                cells.append(ms(v) if v else "-")
            full = [s for s in per_seed if len(per_seed[s]) == len(daghar.DOMAINS)]
            mean = ms([np.mean([per_seed[s][t]["scores"][t]["accuracy"] for t in daghar.DOMAINS]) for s in full])
            any_r = [r for s in per_seed for r in per_seed[s].values()]
            lines.append(f"| {m} | {cost(any_r)} | {','.join(map(str, sorted(full))) or '-'} | " + " | ".join(cells)
                         + f" | **{mean if full else '-'}** |")
        lines.append("")
    return lines


def main(out=os.path.join(ROOT, "RESULTS.md")):
    rows = load()
    lines = ["# Results", "", "Generated by `python tables.py` from `results/`; do not edit by hand. Accuracy and "
             "macro F1 in %, mean ± s.d. over the listed seeds. Model ids: "
             "bifin-w(filters)-k(kernel)-e(embedding)-h(head)[-circ]-(statistical features)[-pooling][-random]; "
             "suffix -keras / -old: runs of the old scripts. params / MFLOPs per window (FIN models: spectral form "
             "when circular, else convolutional; statistical features included).", ""]
    lines += ["## Cross-dataset (10 s windows, WISDM <-> MotionSense)", ""]
    lines += per_test_tables(rows, "cross_dataset", "cross-dataset")
    lines += ["## Within-dataset", ""]
    lines += per_test_tables(rows, "within_dataset", "within-dataset")
    lines += ["## Data scarcity (WISDM, few labelled users)", ""]
    lines += per_test_tables(rows, "scarcity", "data scarcity", best=True)
    lines += ["## DAGHAR", ""]
    lines += daghar_table(rows)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(rows)} results -> {out}")


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=os.path.join(ROOT, "RESULTS.md"))
    main(parser.parse_args().out)
